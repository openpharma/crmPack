#'   are outside of the dose grid range, the information message is printed by
#'   this method.
#'
#' @aliases suggest-NextBestMaxGain
#'
#' @export
#' @example examples/Rules-method-suggest-NextBestMaxGain.R
#'
setMethod(
  f = "suggest",
  signature = signature(
    nextBest = "NextBestMaxGain",
    doselimit = "numeric",
    samples = "missing",
    model = "ModelTox",
    data = "DataDual"
  ),
  definition = function(
    nextBest,
    doselimit = Inf,
    model,
    data,
    model_eff,
    in_sim = FALSE,
    ...
  ) {
    assert_class(model_eff, "Effloglog")
    assert_flag(in_sim)

    # 'drt' - during the trial, 'eot' end of trial.
    prob_target_drt <- nextBest@prob_target_drt
    prob_target_eot <- nextBest@prob_target_eot

