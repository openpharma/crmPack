## generic ----

#' Finding the Next Best Dose
#'
#' @description `r lifecycle::badge("experimental")`
#'
#' A function that computes the recommended next best dose based on the
#' corresponding rule `nextBest`, the posterior `samples` from the `model` and
#' the underlying `data`.
#'
#' This generic method is an evolution of the existing `nextBest` methods.  It
#' returns the same numeric data as `nextBest()`, but in a new object of class
#' `NextBestSuggestion` (or a subclass).  Plots generated by `nextBest()` and
#' returned as an lelemnt of the `list` it returns are/will be generated by new
#' `plot` methods for the `NextBest` class.
#'
#' @param nextBest (`NextBest`)\cr the rule for the next best dose.
#' @param doselimit (`number` or `matrix`)\cr the maximum allowed next dose. If it is
#'   infinity (default), then essentially no dose limit will be applied in the
#'   course of dose recommendation calculation. A `matrix` must be
#'   used for two drug combinations.
#' @param samples (`Samples`)\cr posterior samples from `model` parameters given
#'   `data`.
#' @param model (`GeneralModel`)\cr model that was used to generate the samples.
#' @param data (`Data` or `DataCombo`)\cr data that was used to generate the samples.
#' @param ... additional arguments without method dispatch.
#'
#' @return A list with the next best dose recommendation  (element named `value`)
#'   from the grid defined in `data`, and a plot depicting this recommendation
#'   (element named `plot`). In case of multiple plots also an element
#'   named `singlePlots` is included. The `singlePlots` is itself a list with
#'   single plots. An additional list with elements describing the outcome
#'   of the rule can be contained too.
#'
#' @export
#'
setGeneric(
  name = "suggest",
  def = function(nextBest, doselimit, samples, model, data, ...) {
    if (!missing(doselimit)) {
      if (is.vector(doselimit)) {
        assert_number(doselimit, lower = 0, finite = FALSE)
      } else if (is.matrix(doselimit)) {
        assert_matrix(doselimit, ncols = 2, mode = "numeric")
      } else {
        stop("doselimit must be either a number or a matrix.")
      }
    }
    standardGeneric("suggest")
  },
  valueClass = "NextBestSuggestion"
)

## NextBestEWOC ----

#' @describeIn suggest find the next best dose based on the EWOC rule.
#'
#' @aliases suggest-NextBestEWOC
#'
#' @export
#' @example examples/Rules-method-suggest-NextBestEWOC.R
#'
setMethod(
  f = "suggest",
  signature = signature(
    nextBest = "NextBestEWOC",
    doselimit = "numeric",
    samples = "Samples",
    model = "GeneralModel",
    data = "Data"
  ),
  definition = function(
    nextBest,
    doselimit = Inf,
    samples,
    model,
    data,
    ...
  ) {
    # Matrix with samples from the dose-tox curve at the dose grid points.
    prob_samples <- sapply(
      data@doseGrid,
      prob,
      model = model,
      samples = samples,
      ...
    )

    # Estimates of posterior probabilities that are based on the prob. samples
    # which are within overdose/target interval.
    prob_overdose <- colMeans(h_in_range(
      prob_samples,
      nextBest@overdose,
      bounds_closed = c(FALSE, TRUE)
    ))

    # Eligible grid doses after accounting for maximum possible dose and discarding overdoses.
    is_dose_eligible <- h_next_best_eligible_doses(
      data@doseGrid,
      doselimit,
      data@placebo,
      levels = TRUE
    ) &
      (prob_overdose <= nextBest@max_overdose_prob)

    next_dose <- if (any(is_dose_eligible)) {
      # Take the highest eligible dose.
      next_best_level <- sum(is_dose_eligible)
      data@doseGrid[is_dose_eligible][next_best_level]
    } else {
      NA_real_
    }

    safe_dose <- if (any(is_dose_eligible)) {
      data@doseGrid[sum(is_dose_eligible)]
    } else {
      NA_real_
    }

    # list(
    #   value = next_dose,
    #   plot = p,
    #   singlePlots = list(overdose = p),
    #   probs = cbind(
    #     dose = data@doseGrid,
    #     overdose = prob_overdose
    #   )
    # )

    NextBestSuggestionProbs(
      value = next_dose,
      probs = tibble::tibble(
        Dose = data@doseGrid,
        Overdose = prob_overdose
      )
    )
  }
)


## NextBestMTD ----

#' @describeIn suggest find the next best dose based on the MTD rule.
#'
#' @aliases suggest-NextBestMTD
#'
#' @export
#' @example examples/Rules-method-suggest-NextBestMTD.R
#'
setMethod(
  f = "suggest",
  signature = signature(
    nextBest = "NextBestMTD",
    doselimit = "numeric",
    samples = "Samples",
    model = "GeneralModel",
    data = "Data"
  ),
  definition = function(nextBest, doselimit = Inf, samples, model, data, ...) {
    # Generate the MTD samples and derive the next best dose.
    dose_target_samples <- dose(x = nextBest@target, model, samples, ...)
    dose_target <- nextBest@derive(dose_target_samples)

    # Round to the next possible grid point.
    doses_eligible <- h_next_best_eligible_doses(
      data@doseGrid,
      doselimit,
      data@placebo
    )
    next_dose_level <- which.min(abs(doses_eligible - dose_target))
    next_dose <- doses_eligible[next_dose_level]

    # list(value = next_dose, plot = p)
    NextBestSuggestion(value = next_dose)
  }
)

## NextBestNCRM ----

#' @describeIn suggest find the next best dose based on the NCRM method. The
#'   additional element `probs` in the output's list contains the target and
#'   overdosing probabilities (across all doses in the dose grid) used in the
#'   derivation of the next best dose.
#'
#' @aliases suggest-NextBestNCRM
#'
#' @export
#' @example examples/Rules-method-suggest-NextBestNCRM.R
#'
setMethod(
  f = "suggest",
  signature = signature(
    nextBest = "NextBestNCRM",
    doselimit = "numeric",
    samples = "Samples",
    model = "GeneralModel",
    data = "Data"
  ),
  definition = function(
    nextBest,
    doselimit = Inf,
    samples,
    model,
    data,
    ...
  ) {
    # Matrix with samples from the dose-tox curve at the dose grid points.
    prob_samples <- sapply(
      data@doseGrid,
      prob,
      model = model,
      samples = samples,
      ...
    )

    # Estimates of posterior probabilities that are based on the prob. samples
    # which are within overdose/target interval.
    prob_overdose <- colMeans(
      h_in_range(
        prob_samples,
        nextBest@overdose,
        bounds_closed = c(FALSE, TRUE)
      )
    )
    prob_target <- colMeans(
      h_in_range(prob_samples, nextBest@target)
    )

    # Eligible grid doses after accounting for maximum possible dose and discarding overdoses.
    is_dose_eligible <- h_next_best_eligible_doses(
      data@doseGrid,
      doselimit,
      data@placebo,
      levels = TRUE
    ) &
      (prob_overdose <= nextBest@max_overdose_prob)

    next_dose <- if (any(is_dose_eligible)) {
      # If maximum target probability is higher than some numerical threshold,
      # then take that level, otherwise stick to the maximum level that is OK.
      # next_best_level is relative to eligible doses.
      next_best_level <- ifelse(
        test = any(prob_target[is_dose_eligible] > 0.05),
        yes = which.max(prob_target[is_dose_eligible]),
        no = sum(is_dose_eligible)
      )
      data@doseGrid[is_dose_eligible][next_best_level]
    } else {
      NA_real_
    }

    safe_dose <- if (any(is_dose_eligible)) {
      data@doseGrid[sum(is_dose_eligible)]
    } else {
      NA_real_
    }

    all_target_prob <- rep(NA, nrow(all_dose_matrix))
    all_target_prob[is_below_limit] <- prob_target
    all_overdose_prob <- rep(NA, nrow(all_dose_matrix))
    all_overdose_prob[is_below_limit] <- prob_overdose
    all_not_eligible <- rep(FALSE, nrow(all_dose_matrix))
    all_not_eligible[is_below_limit] <- !is_dose_eligible

    NextBestSuggestionProbs(
      value = next_dose,
      probs = tibble::tibble(
        Dose1 = all_dose_matrix[, 1L],
        Dose2 = all_dose_matrix[, 2L],
        Target = all_target_prob,
        Overdose = all_overdose_prob,
        NotEligible = all_not_eligible
      )
    )
  }
)

## NextBestNCRM-DataCombo ----

#' @describeIn suggest find the next best dose combination based on the NCRM method.
#'
#' @aliases suggest-NextBestNCRM
#'
#' @export
#' @example examples/Rules-method-suggest-NextBestNCRM-DataCombo.R
#'
setMethod(
  f = "suggest",
  signature = signature(
    nextBest = "NextBestNCRM",
    doselimit = "matrix",
    samples = "Samples",
    model = "TwoDrugsCombo",
    data = "DataCombo"
  ),
  definition = function(nextBest, doselimit, samples, model, data, ...) {
    drug_names <- data@drugNames

    # Generate all doses for the combination which are inside the area
    # defined by the dose limit matrix. We don't want to calculate
    # probabilities for doses above the dose limit curve
    # as this will just take unnecessary time.
    all_dose_matrix <- as.matrix(expand.grid(data@doseGrid))
    is_below_limit <- h_dose_combo_below_limit(all_dose_matrix, doselimit)
    dose_matrix <- all_dose_matrix[is_below_limit, , drop = FALSE]

    # Matrix with samples from the dose-tox curve at the dose grid points (rows: samples, cols: doses).
    prob_samples <- apply(
      dose_matrix,
      MARGIN = 1L,
      prob,
      model = model,
      samples = samples,
      ...
    )

    # Estimates of posterior probabilities that are based on the prob. samples
    # which are within overdose/target interval.
    prob_overdose <- colMeans(h_in_range(
      prob_samples,
      nextBest@overdose,
      bounds_closed = c(FALSE, TRUE)
    ))
    prob_target <- colMeans(h_in_range(prob_samples, nextBest@target))

    # Eligible grid doses after accounting for maximum possible dose and discarding overdoses.
    is_dose_eligible <- (prob_overdose <= nextBest@max_overdose_prob)

    next_doses <- if (any(is_dose_eligible)) {
      # If maximum target probability is higher than some numerical threshold,
      # then take that level, otherwise stick to the maximum level that is OK.
      # next_best_level is relative to eligible doses.
      next_best_level <- ifelse(
        test = any(prob_target[is_dose_eligible] > 0.05),
        yes = which.max(prob_target[is_dose_eligible]),
        no = sum(is_dose_eligible) # This selects the one
        # with highest first dose and then highest second dose among
        # the eligible ones.
      )
      dose_matrix[is_dose_eligible, , drop = FALSE][
        next_best_level,
        ,
        drop = TRUE # We want to return a numeric vector, not a matrix!
      ]
    } else {
      NA_real_
    }

    # Build plots, first for the target probability.

    # Show target probability as tiles, and doses that were above
    # the dose limit should stay black.
    all_target_prob <- rep(NA, nrow(all_dose_matrix))
    all_target_prob[is_below_limit] <- prob_target
    all_overdose_prob <- rep(NA, nrow(all_dose_matrix))
    all_overdose_prob[is_below_limit] <- prob_overdose
    all_not_eligible <- rep(FALSE, nrow(all_dose_matrix))
    all_not_eligible[is_below_limit] <- !is_dose_eligible

    plot_data <- setNames(
      data.frame(
        all_dose_matrix[, 1L],
        all_dose_matrix[, 2L],
        all_target_prob,
        all_overdose_prob,
        all_not_eligible
      ),
      c(
        drug_names,
        "target_prob",
        "overdose_prob",
        "not_eligible"
      )
    )
    p1 <- ggplot() +
      geom_tile(
        data = plot_data,
        aes(
          x = .data[[drug_names[1L]]],
          y = .data[[drug_names[2L]]],
          fill = .data$target_prob
        )
      ) +
      scale_fill_gradient(
        low = "white",
        high = "darkgreen",
        na.value = "black",
        limits = c(0, 1),
        name = "Target probability"
      ) +
      xlab(names(data@doseGrid)[1]) +
      ylab(names(data@doseGrid)[2]) +
      geom_point(
        data = plot_data[plot_data$not_eligible, , drop = FALSE],
        aes(x = .data[[drug_names[1L]]], y = .data[[drug_names[2L]]]),
        shape = 4,
        size = 10,
        colour = "red"
      )

    if (any(is_dose_eligible)) {
      p1 <- p1 +
        # And a blue circle on the next best dose.
        geom_point(
          data = data.frame(
            setNames(as.list(next_doses[1:2]), drug_names)
          ),
          aes(x = .data[[drug_names[1L]]], y = .data[[drug_names[2L]]]),
          size = 10,
          shape = 19,
          colour = "blue",
          fill = "blue"
        )
    }

    # Second, for the overdosing probability.
    p2 <- ggplot() +
      geom_tile(
        data = plot_data,
        aes(
          x = .data[[drug_names[1L]]],
          y = .data[[drug_names[2L]]],
          fill = .data$overdose_prob
        )
      ) +
      scale_fill_gradient(
        low = "white",
        high = "red",
        na.value = "black",
        limits = c(0, 1),
        name = "Overdose probability"
      ) +
      xlab(names(data@doseGrid)[1]) +
      ylab(names(data@doseGrid)[2]) +
      geom_point(
        data = plot_data[plot_data$not_eligible, , drop = FALSE],
        aes(x = .data[[drug_names[1L]]], y = .data[[drug_names[2L]]]),
        shape = 4,
        size = 10,
        colour = "red"
      )

    # Place them below each other.
    plot_joint <- h_arrange_plots_aligned(p2, p1, nrow = 2)

    # list(
    #   value = next_doses,
    #   plot = plot_joint,
    #   singlePlots = list(plot1 = p2, plot2 = p1),
    #   probs = plot_data
    # )

    NextBestSuggestionProbs(
      value = next_doses,
      probs = tibble::as_tibble(plot_data)
    )
  }
)

## NextBestNCRM-DataParts ----

#' @describeIn suggest find the next best dose based on the NCRM method when
#'   two parts trial is used.
#'
#' @aliases suggest-NextBestNCRM-DataParts
#'
#' @export
#' @example examples/Rules-method-suggest-NextBestNCRM-DataParts.R
#'
setMethod(
  f = "suggest",
  signature = signature(
    nextBest = "NextBestNCRM",
    doselimit = "numeric",
    samples = "Samples",
    model = "GeneralModel",
    data = "DataParts"
  ),
  definition = function(
    nextBest,
    doselimit = Inf,
    samples,
    model,
    data,
    ...
  ) {
    # Exception when we are in part I or about to start part II!
    if (all(data@part == 1L)) {
      # Propose the highest possible dose (assuming that the dose limit came
      # from reasonable increments rule, i.e. incrementsRelativeParts).
      if (is.infinite(doselimit)) {
        stop("A finite doselimit needs to be specified for Part I.")
      }
      # list(value = doselimit, plot = NULL)
      NextBestSuggestion(value = doselimit)
    } else {
      # Otherwise we will just do the standard thing.
      callNextMethod(
        nextBest,
        doselimit,
        samples,
        model,
        data,
        ...
      )
    }
  }
)

## NextBestNCRMLoss ----

#' @describeIn suggest find the next best dose based on the NCRM method and
#'   loss function.
#'
#' @aliases suggest-NextBestNCRMLoss
#'
#' @export
#' @example examples/Rules-method-suggest-NextBestNCRMLoss.R
#'
setMethod(
  "suggest",
  signature = signature(
    nextBest = "NextBestNCRMLoss",
    doselimit = "numeric",
    samples = "Samples",
    model = "GeneralModel",
    data = "Data"
  ),
  definition = function(
    nextBest,
    doselimit = Inf,
    samples,
    model,
    data,
    ...
  ) {
    # Matrix with samples from the dose-tox curve at the dose grid points.
    prob_samples <- sapply(
      data@doseGrid,
      prob,
      model = model,
      samples = samples,
      ...
    )
    # Compute probabilities to be in target and overdose tox interval.
    prob_underdosing <- colMeans(prob_samples < nextBest@target[1])
    prob_target <- colMeans(h_in_range(prob_samples, nextBest@target))
    prob_overdose <- colMeans(h_in_range(
      prob_samples,
      nextBest@overdose,
      bounds_closed = c(FALSE, TRUE)
    ))
    prob_mean <- colMeans(prob_samples)
    prob_sd <- apply(prob_samples, 2, stats::sd)

    is_unacceptable_specified <- any(nextBest@unacceptable != c(1, 1))

    prob_mat <- if (!is_unacceptable_specified) {
      cbind(
        underdosing = prob_underdosing,
        target = prob_target,
        overdose = prob_overdose
      )
    } else {
      prob_unacceptable <- colMeans(
        h_in_range(
          prob_samples,
          nextBest@unacceptable,
          bounds_closed = c(FALSE, TRUE)
        )
      )
      prob_excessive <- prob_overdose
      prob_overdose <- prob_excessive + prob_unacceptable
      cbind(
        underdosing = prob_underdosing,
        target = prob_target,
        excessive = prob_excessive,
        unacceptable = prob_unacceptable
      )
    }

    posterior_loss <- as.vector(nextBest@losses %*% t(prob_mat))
    names(posterior_loss) <- data@doseGrid

    # Eligible grid doses after accounting for maximum possible dose and discarding overdoses.
    is_dose_eligible <- h_next_best_eligible_doses(
      data@doseGrid,
      doselimit,
      data@placebo,
      levels = TRUE
    ) &
      (prob_overdose < nextBest@max_overdose_prob)

    # Next best dose is the dose with the minimum loss function.
    next_dose <- if (any(is_dose_eligible)) {
      next_best_level <- which.min(posterior_loss[is_dose_eligible])
      data@doseGrid[is_dose_eligible][next_best_level]
    } else {
      NA_real_
    }

    probs <- tibble::tibble(
      Dose = data@doseGrid,
      Underdosing = prob_mat[, "underdosing"],
      Target = prob_mat[, "target"],
      Mean = prob_mean,
      StdDev = prob_sd,
      PosteriorLoss = posterior_loss
    )

    if (is_unacceptable_specified) {
      probs <- probs %>%
        add_column(
          Excessive = prob_mat[, "excessive"],
          .before = 4
        )%>%
        add_column(
          Unacceptable = prob_mat[, "unacceptable"],
          .before = 5
        )
    } else {
      probs <- probs %>%
        add_column(
          Overdose = prob_mat[, "overdose"],
          .before = 4
        )
    }

    # c(list(value = next_dose, probs = probs), p)
    NextBestSuggestionProbs(
      value = next_dose,
      probs = probs
    )
  }
)

## NextBestThreePlusThree ----

#' @describeIn suggest find the next best dose based on the 3+3 method.
#'
#' @aliases suggest-NextBestThreePlusThree
#'
#' @export
#' @example examples/Rules-method-suggest-NextBestThreePlusThree.R
#'
setMethod(
  f = "suggest",
  signature = signature(
    nextBest = "NextBestThreePlusThree",
    doselimit = "missing",
    samples = "missing",
    model = "missing",
    data = "Data"
  ),
  definition = function(nextBest, doselimit, samples, model, data, ...) {
    # The last dose level tested (not necessarily the maximum one).
    last_level <- tail(data@xLevel, 1L)

    # Get number of patients per grid's dose and DLT rate at the last level.
    nPatients <- table(factor(data@x, levels = data@doseGrid))
    n_dlts_last_level <- sum(data@y[data@xLevel == last_level])
    dlt_rate_last_level <- n_dlts_last_level / nPatients[last_level]

    level_change <- if (dlt_rate_last_level < 1 / 3) {
      # Escalate it, unless this is the highest level or the higher dose was already tried.
      ifelse(
        (last_level == data@nGrid) || (nPatients[last_level + 1L] > 0),
        0L,
        1L
      )
    } else {
      # Rate is too high, deescalate it, unless an edge case of 1/3, where the decision
      # depends on the num. of patients: if >3, then deescalate it, otherwise stay.
      ifelse(
        (dlt_rate_last_level == 1 / 3) && (nPatients[last_level] <= 3L),
        0L,
        -1L
      )
    }
    next_dose_level <- last_level + level_change

    # Do we stop here? Only if we have no MTD, or the next level has been tried
    # enough (more than three patients already).
    if (next_dose_level == 0L) {
      next_dose <- NA_real_
      stop_here <- TRUE
    } else {
      next_dose <- data@doseGrid[next_dose_level]
      stop_here <- nPatients[next_dose_level] > 3L
    }

    NextBestSuggestionThreePlusThree(value = next_dose, stopHere = stop_here)
  }
)

## NextBestDualEndpoint ----

#' @describeIn suggest find the next best dose based on the dual endpoint
#'   model. The additional list element `probs` contains the target and
#'   overdosing probabilities (across all doses in the dose grid) used in the
#'   derivation of the next best dose.
#'
#' @aliases suggest-NextBestDualEndpoint
#'
#' @export
#' @example examples/Rules-method-suggest-NextBestDualEndpoint.R
#'
setMethod(
  f = "suggest",
  signature = signature(
    nextBest = "NextBestDualEndpoint",
    doselimit = "numeric",
    samples = "Samples",
    model = "DualEndpoint",
    data = "Data"
  ),
  definition = function(
    nextBest,
    doselimit = Inf,
    samples,
    model,
    data,
    ...
  ) {
    # Biomarker samples at the dose grid points.
    biom_samples <- samples@data$betaW

    prob_target <- if (nextBest@target_relative) {
      # If 'Emax' parameter available, target biomarker level will be relative to 'Emax',
      # otherwise, it will be relative to the maximum biomarker level achieved
      # in dose range for a given sample.
      if ("Emax" %in% names(samples)) {
        lwr <- nextBest@target[1] * samples@data$Emax
        upr <- nextBest@target[2] * samples@data$Emax
        colMeans(apply(biom_samples, 2L, function(s) (s >= lwr) & (s <= upr)))
      } else {
        target_levels <- apply(biom_samples, 1L, function(x) {
          rng <- range(x)
          min(which(h_in_range(
            x,
            nextBest@target * diff(rng) + rng[1] + c(0, 1e-10),
            bounds_closed = c(FALSE, TRUE)
          )))
        })
        prob_target <- as.vector(table(factor(
          target_levels,
          levels = 1:data@nGrid
        )))
        prob_target / nrow(biom_samples)
      }
    } else {
      colMeans(h_in_range(biom_samples, nextBest@target))
    }

    # Now, compute probabilities to be in overdose tox interval, then flag
    # eligible grid doses after accounting for maximum possible dose and discarding overdoses.
    prob_samples <- sapply(
      data@doseGrid,
      prob,
      model = model,
      samples = samples
    )
    prob_overdose <- colMeans(h_in_range(
      prob_samples,
      nextBest@overdose,
      bounds_closed = c(FALSE, TRUE)
    ))

    is_dose_eligible <- h_next_best_eligible_doses(
      data@doseGrid,
      doselimit,
      data@placebo,
      levels = TRUE
    ) &
      (prob_overdose < nextBest@max_overdose_prob)

    next_dose <- if (any(is_dose_eligible)) {
      # If maximum target probability is higher the threshold, then take that
      # level, otherwise stick to the maximum level that is eligible.
      # next_dose_level is relative to eligible doses.
      next_dose_level <- ifelse(
        test = any(prob_target[is_dose_eligible] > nextBest@target_thresh),
        yes = which.max(prob_target[is_dose_eligible]),
        no = sum(is_dose_eligible)
      )
      data@doseGrid[is_dose_eligible][next_dose_level]
    } else {
      NA_real_
    }

    # Build plots, first for the target probability. Reference lines are added
    # before the probability geometry so it remains visible where layers overlap.
    safe_dose <- if (any(is_dose_eligible)) {
      data@doseGrid[sum(is_dose_eligible)]
    } else {
      NA_real_
    }

    NextBestSuggestionProbs(
      value = next_dose,
      tibble::tibble(
        Dose = data@doseGrid,
        Target = prob_target,
        Overdose = prob_overdose
      )
    )
  }
)

## NextBestMinDist ----

#' @describeIn suggest gives the dose which is below the dose limit and has an
#'   estimated DLT probability which is closest to the target dose.
#'
#' @aliases suggest-NextBestMinDist
#'
#' @export
#'
setMethod(
  f = "suggest",
  signature = signature(
    nextBest = "NextBestMinDist",
    doselimit = "numeric",
    samples = "Samples",
    model = "GeneralModel",
    data = "Data"
  ),
  definition = function(nextBest, doselimit = Inf, samples, model, data, ...) {
    # Matrix with samples from the dose-tox curve at the dose grid points.
    prob_samples <- sapply(
      data@doseGrid,
      prob,
      model = model,
      samples = samples,
      ...
    )
    dlt_prob <- colMeans(prob_samples)

    # Determine the dose with the closest distance.
    dose_target <- data@doseGrid[which.min(abs(dlt_prob - nextBest@target))]

    # Determine next dose.
    doses_eligible <- h_next_best_eligible_doses(
      data@doseGrid,
      doselimit,
      data@placebo
    )
    next_dose_level_eligible <- which.min(abs(doses_eligible - dose_target))
    next_dose <- doses_eligible[next_dose_level_eligible]

    NextBestSuggestionProbs(
      value = next_dose,
      probs = tibble::tibble(
        Dose = data@doseGrid,
        DLT = dlt_prob
      )
    )
  }
)

## NextBestInfTheory ----

#' @describeIn suggest gives the appropriate dose within an information
#'   theoretic framework.
#'
#' @aliases suggest-NextBestInfTheory
#'
#' @export
#'
setMethod(
  f = "suggest",
  signature = signature(
    nextBest = "NextBestInfTheory",
    doselimit = "numeric",
    samples = "Samples",
    model = "GeneralModel",
    data = "Data"
  ),
  definition = function(nextBest, doselimit = Inf, samples, model, data, ...) {
    # Matrix with samples from the dose-tox curve at the dose grid points.
    prob_samples <- sapply(
      data@doseGrid,
      prob,
      model = model,
      samples = samples,
      ...
    )

    criterion <- colMeans(h_info_theory_dist(
      prob_samples,
      nextBest@target,
      nextBest@asymmetry
    ))

    is_dose_eligible <- h_next_best_eligible_doses(
      data@doseGrid,
      doselimit,
      data@placebo,
      levels = TRUE
    )
    doses_eligible <- data@doseGrid[is_dose_eligible]
    next_best_level <- which.min(criterion[is_dose_eligible])
    next_best <- doses_eligible[next_best_level]

    # list(value = next_best)
    NextBestSuggestion(value = next_best)
  }
)

## NextBestTD ----

#' @describeIn suggest find the next best dose based only on the DLT responses
#'   and for [`LogisticIndepBeta`] model class object without DLT samples.
#'
#' @param model (`ModelTox`)\cr the DLT model.
#' @param in_sim (`flag`)\cr is this method used in simulations? Default as `FALSE`.
#'   If this flag is `TRUE` and target dose estimates (during trial and end-of-trial)
#'   are outside of the dose grid range, the information message is printed by
#'   this method.
#'
#' @aliases suggest-NextBestTD
#'
#' @export
#' @example examples/Rules-method-suggest-NextBestTD.R
#'
setMethod(
  f = "suggest",
  signature = signature(
    nextBest = "NextBestTD",
    doselimit = "numeric",
    samples = "missing",
    model = "LogisticIndepBeta",
    data = "Data"
  ),
  definition = function(
    nextBest,
    doselimit = Inf,
    model,
    data,
    in_sim = FALSE,
    ...
  ) {
    assert_flag(in_sim)

    # 'drt' - during the trial, 'eot' end of trial.
    prob_target_drt <- nextBest@prob_target_drt
    prob_target_eot <- nextBest@prob_target_eot

    # Target dose estimates, i.e. the dose with probability of the occurrence of
    # a DLT that equals to the prob_target_drt or prob_target_eot.
    dose_target_drt <- dose(x = prob_target_drt, model, ...)
    dose_target_eot <- dose(x = prob_target_eot, model, ...)

    # Find the next best doses in the doseGrid. The next best dose is the dose
    # at level closest and below the target dose estimate.
    # h_find_interval assumes that elements in doses_eligible are strictly increasing.
    doses_eligible <- h_next_best_eligible_doses(
      data@doseGrid,
      doselimit,
      data@placebo
    )

    next_dose_lev_drt <- h_find_interval(dose_target_drt, doses_eligible)
    next_dose_drt <- doses_eligible[next_dose_lev_drt]

    next_dose_lev_eot <- h_find_interval(dose_target_eot, doses_eligible)
    next_dose_eot <- doses_eligible[next_dose_lev_eot]

    # Find the variance of the log of the dose_target_eot.
    mat <- matrix(
      c(
        -1 / (model@phi2),
        -(log(prob_target_eot / (1 - prob_target_eot)) - model@phi1) /
          (model@phi2)^2
      ),
      nrow = 1
    )
    var_dose_target_eot <- as.vector(mat %*% model@Pcov %*% t(mat))

    # 95% credibility interval.
    ci_dose_target_eot <- exp(
      log(dose_target_eot) + c(-1, 1) * 1.96 * sqrt(var_dose_target_eot)
    )
    cir_dose_target_eot <- ci_dose_target_eot[2] / ci_dose_target_eot[1]

    if (
      !h_in_range(
        dose_target_drt,
        range = dose_grid_range(data),
        bounds_closed = TRUE
      ) &&
        !in_sim
    ) {
      warning(paste(
        "TD",
        prob_target_drt * 100,
        "=",
        dose_target_drt,
        "not within dose grid"
      ))
    }
    if (
      !h_in_range(
        dose_target_eot,
        range = dose_grid_range(data),
        bounds_closed = TRUE
      ) &&
        !in_sim
    ) {
      warning(paste(
        "TD",
        prob_target_eot * 100,
        "=",
        dose_target_eot,
        "not within dose grid"
      ))
    }

    # list(
    #   next_dose_drt = next_dose_drt,
    #   prob_target_drt = prob_target_drt,
    #   dose_target_drt = dose_target_drt,
    #   next_dose_eot = next_dose_eot,
    #   prob_target_eot = prob_target_eot,
    #   dose_target_eot = dose_target_eot,
    #   ci_dose_target_eot = ci_dose_target_eot,
    #   ci_ratio_dose_target_eot = cir_dose_target_eot,
    #   plot = p
    # )
    warning("Check return value of suggest-NextBestTD")
    NextBestSuggestion(value = next_dose_drt)
  }
)

